  '수학·과학·사회·국어·정보·보건 체육·음악·미술 용어를 뜻과 수업에서 쓰이는 방식과 함께 배워요. 답한 뒤의 설명에 선생님이 수업에서 할 법한 문장이 실려 있어요.',
