# Builds parts/f17_sdlang.js and i18n/{en,ko,zh}/sdlang.tsv: 授業の用語(くわしく) for the other languages.
#   cd app/babel-flight/sd && python3 gen_sdl.py [--write]
# A language with only sdl_<L>.py (the 128 core terms: 8 subjects x 16) gets 2 banks of 64.
# A language that also has sdx_<L>*.py (the other 384 terms, and the 国語 terms of sd_alt) gets the English course's
# layout: 8 banks (one per subject) x 8 units x 8 terms, the units named like the English ones.
# Entry: key -> (term, reading, class sentence) and the sentence's translations come from the English course;
#        key -> (term, reading, sentence, 日本語訳, 한국어, 中文, English) for the sentences of the language's own (sd_alt.OWN, ALT).
