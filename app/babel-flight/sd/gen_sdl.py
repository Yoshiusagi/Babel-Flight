EN_FULL = {'ma': ('Math', 'Numbers & expressions · shapes · functions · probability & data'), 'sc': ('Science', 'Physics · chemistry · biology · earth science'),
           'so': ('Social studies', 'Geography · history · government · economics'), 'la': ('Language arts', 'Grammar · reading & literature · writing · speaking'),
           'it': ('Computing', 'Computers · programming · networks · data'), 'pe': ('P.E. and health', 'The body · health · first aid · sports'),
           'mu': ('Music', 'Reading music · instruments · performance · genres & composing'), 'ar': ('Art', 'Drawing · color · materials & techniques · design · appreciation')}
for c, (jp, topics) in FULL.items():   # bank titles and subjects: Korean and Chinese from the English course's translations
    en, en_sub = EN_FULL[c]
    for k, e in ((jp + 'の用語(くわしく)', en + ' terms (in depth)'), (jp + 'の用語', en + ' terms')):
        if not any(x[0] == k for x in EXTRA):
            if k not in HAVE['ko'] or k not in HAVE['zh']: bad.append(('tsv', k))
            else: EXTRA.append((k, HAVE['ko'][k], HAVE['zh'][k], e))
    sub = {u: (HAVE[u].get(topics + ' ・ 英語') or '').rsplit(' · ', 1)[0] for u in ('ko', 'zh')}
    if all(sub.values()): EXTRA.append((topics, sub['ko'], sub['zh'], en_sub))
    else: bad.append(('sub', topics, sub))
for j, k, z, e in EXTRA:
    tsv['ko'].append(j + '\t' + k); tsv['zh'].append(j + '\t' + z); tsv['en'].append(j + '\t' + e)
for u in tsv:   # a text another .tsv already translates keeps that translation; the same key twice must agree
    keep, mine = [tsv[u][0]], {}
    for line in tsv[u][1:]:
        k, v = line.split('\t')
        if KANA.search(v): bad.append((u, k, v))
        if k in HAVE[u]:
            if HAVE[u][k] != v and not re.search('授業では', k): print('kept existing', u, k, '->', HAVE[u][k], '| mine:', v)
            continue
        if k in mine:
            if mine[k] != v: print('conflict', u, k, mine[k], v)
            continue
        mine[k] = v; keep.append(line)
    tsv[u] = keep
print(' / '.join(report), '| terms', total, '| bad', len(bad))
for b in bad[:30]: print('BAD', b)
if '--write' in sys.argv and not bad:
    open(APP + '/parts/f17_sdlang.js', 'w').write('\n'.join(js) + '\n')
    for u in tsv: open(APP + '/i18n/%s/sdlang.tsv' % u, 'w').write('\n'.join(tsv[u]) + '\n')
    print('wrote')
